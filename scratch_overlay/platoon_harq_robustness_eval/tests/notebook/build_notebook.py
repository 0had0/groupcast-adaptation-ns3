def ledger_row(fid):
    cs = [(tid, c) for tid, j in RESULTS.items() for c in j["checks"] if re.search(r"\b" + fid + r"\b", c.get("finding") or "")]
    tests = ",".join(sorted({t for t, _ in cs}))
    sts = [c["status"] for _, c in cs]
    if fid in MANUAL:
        v, t, ev = MANUAL[fid]
        return dict(id=fid, finding=DESC[fid], verdict=v, tests=t, evidence=ev)
    if not cs:
        return dict(id=fid, finding=DESC[fid], verdict="not tested", tests="-", evidence="no check carries this finding id")
    if "FAIL" in sts:
        v = "confirmed (FAIL)"
    elif "XFAIL" in sts:
        v = "confirmed"
    elif "PASS" in sts:
        v = "refuted"
    else:
        v = "observed (INFO)"
    pri = {"FAIL": 0, "XFAIL": 1, "PASS": 2, "INFO": 3, "SKIP": 4}
    cs.sort(key=lambda x: pri[x[1]["status"]])
    t, c = cs[0]
    ev = f"{t} {c['status']}: {trunc(c['name'], 100)} -> {trunc(c.get('observed'), 150)}"
    if len(cs) > 1:
        ev += f"  (+{len(cs) - 1} more checks: { {k: int(v) for k, v in pd.Series(sts).value_counts().items()} })"
    return dict(id=fid, finding=DESC[fid], verdict=v, tests=tests, evidence=ev)


